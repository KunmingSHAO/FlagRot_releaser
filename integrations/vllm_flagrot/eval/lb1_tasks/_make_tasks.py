"""Generate the LongBench v1 task yamls of this directory (lm-eval --include_path).

  python integrations/vllm_flagrot/eval/lb1_tasks/_make_tasks.py

Each lb1_<task>.yaml = lm-eval 0.4.13 tasks/longbench/<task>.yaml (max_gen_toks, stop sequences, metric functions,
metric_list, greedy decoding) with the PROMPT and DATA of the official LongBench code (THUDM/LongBench, LongBench/pred.py):
lm-eval's longbench tasks read Xnhyacinth/LongBench, whose `context` / `question` fields are already formatted with the
official instruction text (context + question + answer_prefix == the official prompt, checked for all 4750 items except
triviaqa / samsum, which repeat the answer prefix), and wrap them in the official template again -> every lm-eval prompt
repeats the instruction (0 / 4750 equal to the official prompt). Here the prompt is official/dataset2prompt.json
formatted with the official data (THUDM/LongBench data.zip, same items / answers as lm-eval's), middle-truncated as in
pred.py (lb1_utils.py). max_gen_toks is asserted equal to official/dataset2maxlen.json.
"""
import json
from pathlib import Path

import lm_eval
import lm_eval.tasks
import yaml

HERE = Path(__file__).resolve().parent
SRC = Path(lm_eval.tasks.__file__).parent / "longbench"
TASKS = ["narrativeqa", "qasper", "multifieldqa_en", "multifieldqa_zh", "hotpotqa", "2wikimqa", "musique", "dureader",
         "gov_report", "qmsum", "multi_news", "vcsum", "trec", "triviaqa", "samsum", "lsht", "passage_count",
         "passage_retrieval_en", "passage_retrieval_zh", "lcc", "repobench-p"]


class _Fn(str):
    pass


yaml.SafeLoader.add_constructor("!function", lambda loader, node: _Fn(loader.construct_scalar(node)))
yaml.SafeDumper.add_representer(_Fn, lambda dumper, data: dumper.represent_scalar("!function", str(data)))


def main():
    maxlen = json.loads((HERE / "official/dataset2maxlen.json").read_text())
    for t in TASKS:
        src = yaml.safe_load((SRC / f"{t}.yaml").read_text())
        assert src["dataset_name"] == t and src["dataset_path"] == "Xnhyacinth/LongBench", t
        assert src["generation_kwargs"]["max_gen_toks"] == maxlen[t], t
        fn = str(src["process_results"]).split(".", 1)[1]           # metrics.get_* -> lb1_utils.get_*
        out = dict(task=f"lb1_{t}", dataset_path="", dataset_name="", test_split="test", output_type="generate_until",
                   custom_dataset=_Fn("lb1_utils.load_" + t.replace("-", "_")),
                   doc_to_text=_Fn("lb1_utils.doc_to_text"), doc_to_target=src["doc_to_target"])
        if "target_delimiter" in src:
            out["target_delimiter"] = src["target_delimiter"]
        out.update(process_results=_Fn("lb1_utils." + fn), generation_kwargs=src["generation_kwargs"],
                   metric_list=src["metric_list"],
                   metadata=dict(src.get("metadata", {}), source=f"lm_eval {lm_eval.__version__} tasks/longbench/{t}.yaml"
                                 " + official prompt / data / middle truncation"))
        (HERE / f"lb1_{t}.yaml").write_text(
            f"# generated by _make_tasks.py from lm-eval tasks/longbench/{t}.yaml (official prompt + middle truncation)\n"
            + yaml.safe_dump(out, sort_keys=False, allow_unicode=True, width=1000))
    print("wrote", len(TASKS), "tasks to", HERE)


if __name__ == "__main__":
    main()
