"""generate csrc/mq_wgmma.h: wgmma f16 wrappers of mq_prefill.cu (k_mq2, k_mq3)."""
import sys

out = ["// generated by gen_mq_wgmma.py: wgmma f16 -> f32 wrappers of mq_prefill.cu (k_mq2), no swizzle, K-major",
       "#pragma once", ""]


def regs(n, start=0, plus=False):
    return ", ".join(f'"{"+" if plus else "="}f"(d[{i}])' for i in range(n))


# SS m64n64k16: S = Q K^T (scale-d 0: overwrite, 1: accumulate)
for sd in (0, 1):
    n = 32
    dl = ",".join(f"%{i}" for i in range(n))
    out.append(f"DEVI void wg_ss_f16_n64_{sd}(float (&d)[32], uint64_t a, uint64_t b) {{")
    out.append(f'  asm volatile("wgmma.mma_async.sync.aligned.m64n64k16.f32.f16.f16 {{{dl}}}, %{n}, %{n + 1}, {sd}, 1, 1, 0, 0;\\n"')
    out.append(f'               : {regs(n, plus=bool(sd))}')
    out.append('               : "l"(a), "l"(b));')
    out.append("}")
# RS m64n128k16: O += P V (A = P from registers)
n = 64
dl = ",".join(f"%{i}" for i in range(n))
out.append("DEVI void wg_rs_f16_n128(float (&d)[64], const uint32_t (&a)[4], uint64_t b) {")
out.append(f'  asm volatile("wgmma.mma_async.sync.aligned.m64n128k16.f32.f16.f16 {{{dl}}}, {{%{n},%{n + 1},%{n + 2},%{n + 3}}}, %{n + 4}, 1, 1, 1, 0;\\n"')
out.append(f'               : {regs(n, plus=True)}')
out.append('               : "r"(a[0]), "r"(a[1]), "r"(a[2]), "r"(a[3]), "l"(b));')
out.append("}")
# RS m64n256k16: O += P V at head size 256 (k_mq3)
n = 128
dl = ",".join(f"%{i}" for i in range(n))
out.append("DEVI void wg_rs_f16_n256(float (&d)[128], const uint32_t (&a)[4], uint64_t b) {")
out.append(f'  asm volatile("wgmma.mma_async.sync.aligned.m64n256k16.f32.f16.f16 {{{dl}}}, {{%{n},%{n + 1},%{n + 2},%{n + 3}}}, %{n + 4}, 1, 1, 1, 0;\\n"')
out.append(f'               : {regs(n, plus=True)}')
out.append('               : "r"(a[0]), "r"(a[1]), "r"(a[2]), "r"(a[3]), "l"(b));')
out.append("}")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
